function interpolateYucoreCopy(
  value: string,
  options?: Parameters<ReturnType<typeof useTranslation>['t']>[1]
) {
  if (typeof options !== 'object' || options === null) return value

  const replacements = options as Record<string, unknown>

  return value.replaceAll(/\{\{\s*([\w.]+)\s*\}\}/g, (match, key: string) => {
    const replacement = replacements[key]
    return replacement === undefined || replacement === null
      ? match
      : String(replacement)
  })
}

export function useYucoreTranslation() {
  const translation = useTranslation()
  const locale = normalizeInterfaceLanguage(
    translation.i18n.resolvedLanguage ?? translation.i18n.language
  )
  const copy = locale === 'en' ? undefined : yucoreCopy[locale as YucoreLocale]

  const t = (key: string, options?: Parameters<typeof translation.t>[1]) => {
    const localCopy = copy?.[key]

    if (!localCopy) {
      return typeof options === 'string'
        ? translation.t(key, options)
        : translation.t(key, options)
    }
    return interpolateYucoreCopy(localCopy, options)
  }

  return {
    ...translation,
    t,
  }
}
